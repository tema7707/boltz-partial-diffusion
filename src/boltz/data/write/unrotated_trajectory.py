"""
Post-processing module for creating unrotated trajectories with fixed chains.

This module implements a clean post-processing approach to handle fixed chains:
1. Load a trajectory generated by normal diffusion sampling
2. Identify fixed chains that should remain stationary
3. Compute optimal transformations to align fixed chains to their original positions
4. Apply these transformations to generate an "unrotated" trajectory
5. Save the unrotated trajectory as a separate file

This approach is much cleaner than modifying the diffusion process itself.
"""

import numpy as np
import torch
from pathlib import Path
from typing import List, Optional, Dict, Any, Tuple, Union
from scipy.spatial.transform import Rotation
from .trajectory import TrajectoryWriter


class UnrotatedTrajectoryProcessor:
    """Post-processor for creating unrotated trajectories with fixed chains."""
    
    def __init__(self, output_dir: Path, record_id: str):
        """Initialize the unrotated trajectory processor.
        
        Args:
            output_dir: Directory containing trajectory files
            record_id: Unique identifier for this trajectory
        """
        self.output_dir = Path(output_dir)
        self.record_id = record_id
        self.trajectory_dir = self.output_dir / "trajectories"
        
    def process_fixed_chains(self, 
                           fixed_chains: List[str],
                           reference_pdb: Optional[Path] = None,
                           trajectory_type: str = "denoised") -> Optional[Path]:
        """
        Create an unrotated trajectory where fixed chains remain in their original positions.
        
        Args:
            fixed_chains: List of chain letters that should remain fixed (e.g., ['B'])
            reference_pdb: Path to reference PDB with original positions (optional)
            trajectory_type: Type of trajectory to process ("denoised" or "raw")
            
        Returns:
            Path to the unrotated trajectory file, or None if processing failed
        """
        print(f"[UnrotatedTrajectory] Processing fixed chains: {fixed_chains}")
        
        # Load the original trajectory
        trajectory_path = self.trajectory_dir / f"{self.record_id}_trajectory_{trajectory_type}.pdb"
        if not trajectory_path.exists():
            print(f"[UnrotatedTrajectory] Trajectory file not found: {trajectory_path}")
            return None
            
        # Parse the trajectory
        frames = self._parse_trajectory_pdb(trajectory_path)
        if not frames:
            print(f"[UnrotatedTrajectory] Failed to parse trajectory")
            return None
            
        print(f"[UnrotatedTrajectory] Loaded {len(frames)} trajectory frames")
        
        # Get reference positions for fixed chains
        reference_positions = self._get_reference_positions(fixed_chains, reference_pdb, frames[0])
        if not reference_positions:
            print(f"[UnrotatedTrajectory] Failed to get reference positions")
            return None
            
        # Create unrotated trajectory
        unrotated_frames = self._create_unrotated_trajectory(
            frames, fixed_chains, reference_positions
        )
        
        if not unrotated_frames:
            print(f"[UnrotatedTrajectory] Failed to create unrotated trajectory")
            return None
            
        # Save unrotated trajectory
        unrotated_path = self._save_unrotated_trajectory(
            unrotated_frames, f"{trajectory_type}_unrotated"
        )
        
        return unrotated_path
        
    def _parse_trajectory_pdb(self, trajectory_path: Path) -> List[List[Dict]]:
        """Parse multi-model PDB trajectory into frames."""
        frames = []
        current_frame = []
        
        try:
            with open(trajectory_path, 'r') as f:
                for line in f:
                    if line.startswith('MODEL'):
                        if current_frame:  # Save previous frame
                            frames.append(current_frame.copy())
                        current_frame = []
                    elif line.startswith('ATOM  '):
                        atom_record = {
                            'atom_num': int(line[6:11].strip()),
                            'atom_name': line[12:16].strip(),
                            'res_name': line[17:20].strip(),
                            'chain_id': line[21].strip() or 'A',
                            'res_num': int(line[22:26].strip()),
                            'coords': np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])]),
                            'element': line[76:78].strip() or line[12:16].strip()[0]
                        }
                        current_frame.append(atom_record)
                    elif line.startswith('ENDMDL') or line.startswith('END'):
                        if current_frame:
                            frames.append(current_frame.copy())
                            current_frame = []
                            
            # Handle last frame if no ENDMDL
            if current_frame:
                frames.append(current_frame)
                
        except Exception as e:
            print(f"[UnrotatedTrajectory] Error parsing trajectory: {e}")
            return []
            
        return frames
        
    def _get_reference_positions(self, 
                               fixed_chains: List[str],
                               reference_pdb: Optional[Path],
                               first_frame: List[Dict]) -> Dict[str, np.ndarray]:
        """Get reference positions for fixed chains."""
        reference_positions = {}
        
        if reference_pdb and reference_pdb.exists():
            # Load reference positions from provided PDB
            print(f"[UnrotatedTrajectory] Loading reference from: {reference_pdb}")
            reference_atoms = self._parse_reference_pdb(reference_pdb)
        else:
            # Use first frame as reference (assuming it's closest to original)
            print(f"[UnrotatedTrajectory] Using first frame as reference")
            reference_atoms = first_frame
            
        # Extract positions for fixed chains
        for chain_id in fixed_chains:
            chain_atoms = [atom for atom in reference_atoms if atom['chain_id'] == chain_id]
            if chain_atoms:
                coords = np.array([atom['coords'] for atom in chain_atoms])
                reference_positions[chain_id] = coords
                print(f"[UnrotatedTrajectory] Chain {chain_id}: {len(chain_atoms)} reference atoms")
            else:
                print(f"[UnrotatedTrajectory] Warning: No atoms found for fixed chain {chain_id}")
                
        return reference_positions
        
    def _parse_reference_pdb(self, reference_pdb: Path) -> List[Dict]:
        """Parse reference PDB file."""
        atoms = []
        
        try:
            with open(reference_pdb, 'r') as f:
                for line in f:
                    if line.startswith('ATOM  '):
                        atom_record = {
                            'atom_num': int(line[6:11].strip()),
                            'atom_name': line[12:16].strip(),
                            'res_name': line[17:20].strip(),
                            'chain_id': line[21].strip() or 'A',
                            'res_num': int(line[22:26].strip()),
                            'coords': np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])]),
                            'element': line[76:78].strip() or line[12:16].strip()[0]
                        }
                        atoms.append(atom_record)
        except Exception as e:
            print(f"[UnrotatedTrajectory] Error parsing reference PDB: {e}")
            return []
            
        return atoms
        
    def _create_unrotated_trajectory(self, 
                                   frames: List[List[Dict]],
                                   fixed_chains: List[str],
                                   reference_positions: Dict[str, np.ndarray]) -> List[List[Dict]]:
        """Create unrotated trajectory by aligning fixed chains to reference positions."""
        unrotated_frames = []
        
        for frame_idx, frame in enumerate(frames):
            print(f"[UnrotatedTrajectory] Processing frame {frame_idx + 1}/{len(frames)}")
            
            # Get current positions of fixed chains
            current_positions = {}
            for chain_id in fixed_chains:
                chain_atoms = [atom for atom in frame if atom['chain_id'] == chain_id]
                if chain_atoms:
                    coords = np.array([atom['coords'] for atom in chain_atoms])
                    current_positions[chain_id] = coords
                    
            # Compute optimal transformation to align fixed chains
            transformation = self._compute_alignment_transformation(
                current_positions, reference_positions, fixed_chains
            )
            
            if transformation is None:
                print(f"[UnrotatedTrajectory] Warning: Could not compute transformation for frame {frame_idx}")
                unrotated_frames.append(frame)  # Use original frame
                continue
                
            # Apply transformation to all atoms in the frame
            unrotated_frame = []
            for atom in frame:
                new_coords = self._apply_transformation(atom['coords'], transformation)
                new_atom = atom.copy()
                new_atom['coords'] = new_coords
                unrotated_frame.append(new_atom)
                
            unrotated_frames.append(unrotated_frame)
            
        return unrotated_frames
        
    def _compute_alignment_transformation(self, 
                                        current_positions: Dict[str, np.ndarray],
                                        reference_positions: Dict[str, np.ndarray],
                                        fixed_chains: List[str]) -> Optional[Dict]:
        """Compute optimal rigid transformation to align current fixed chains to reference."""
        
        # Collect all fixed chain atoms
        current_coords = []
        reference_coords = []
        
        for chain_id in fixed_chains:
            if chain_id in current_positions and chain_id in reference_positions:
                curr = current_positions[chain_id]
                ref = reference_positions[chain_id]
                
                # Ensure same number of atoms
                min_atoms = min(len(curr), len(ref))
                current_coords.append(curr[:min_atoms])
                reference_coords.append(ref[:min_atoms])
                
        if not current_coords:
            return None
            
        # Concatenate all coordinates
        current_all = np.concatenate(current_coords, axis=0)
        reference_all = np.concatenate(reference_coords, axis=0)
        
        # Compute optimal rigid transformation using Kabsch algorithm
        transformation = self._kabsch_algorithm(current_all, reference_all)
        return transformation
        
    def _kabsch_algorithm(self, P: np.ndarray, Q: np.ndarray) -> Dict:
        """
        Compute optimal rotation and translation using Kabsch algorithm.
        
        Args:
            P: Current coordinates (N x 3)
            Q: Reference coordinates (N x 3)
            
        Returns:
            Dictionary with 'rotation' (3x3) and 'translation' (3,) arrays
        """
        # Center the coordinates
        P_centered = P - np.mean(P, axis=0)
        Q_centered = Q - np.mean(Q, axis=0)
        
        # Compute covariance matrix
        H = P_centered.T @ Q_centered
        
        # SVD
        U, S, Vt = np.linalg.svd(H)
        
        # Compute optimal rotation
        R = Vt.T @ U.T
        
        # Ensure proper rotation (det(R) = 1)
        if np.linalg.det(R) < 0:
            Vt[-1, :] *= -1
            R = Vt.T @ U.T
            
        # Compute optimal translation
        t = np.mean(Q, axis=0) - R @ np.mean(P, axis=0)
        
        return {
            'rotation': R,
            'translation': t
        }
        
    def _apply_transformation(self, coords: np.ndarray, transformation: Dict) -> np.ndarray:
        """Apply rigid transformation to coordinates."""
        R = transformation['rotation']
        t = transformation['translation']
        
        # Apply rotation then translation
        transformed = R @ coords + t
        return transformed
        
    def _save_unrotated_trajectory(self, 
                                 unrotated_frames: List[List[Dict]],
                                 trajectory_type: str) -> Optional[Path]:
        """Save unrotated trajectory as PDB file."""
        try:
            output_path = self.trajectory_dir / f"{self.record_id}_trajectory_{trajectory_type}.pdb"
            
            with open(output_path, 'w') as f:
                # Write header
                f.write(f"HEADER    UNROTATED DIFFUSION TRAJECTORY\n")
                f.write(f"TITLE     BOLTZ UNROTATED TRAJECTORY (FIXED CHAINS)\n")
                f.write(f"REMARK   1 TRAJECTORY TYPE: {trajectory_type.upper()}\n")
                f.write(f"REMARK   1 NUMBER OF FRAMES: {len(unrotated_frames)}\n")
                f.write(f"REMARK   1 POST-PROCESSED TO KEEP FIXED CHAINS STATIONARY\n")
                f.write(f"REMARK   1 GENERATED BY BOLTZ UNROTATED TRAJECTORY PROCESSOR\n")
                
                for frame_idx, frame in enumerate(unrotated_frames):
                    f.write(f"MODEL     {frame_idx + 1:4d}\n")
                    
                    for atom in frame:
                        x, y, z = atom['coords']
                        f.write(f"ATOM  {atom['atom_num']:5d} {atom['atom_name']:>4s} "
                               f"{atom['res_name']:>3s} {atom['chain_id']:>1s}{atom['res_num']:4d}    "
                               f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00 20.00          "
                               f"{atom['element']:>2s}\n")
                    
                    f.write("ENDMDL\n")
                    
                f.write("END\n")
                
            print(f"[UnrotatedTrajectory] Saved unrotated trajectory: {output_path}")
            return output_path
            
        except Exception as e:
            print(f"[UnrotatedTrajectory] Error saving unrotated trajectory: {e}")
            return None


def create_unrotated_trajectory(output_dir: Path, 
                              record_id: str,
                              fixed_chains: List[str],
                              reference_pdb: Optional[Path] = None,
                              trajectory_type: str = "denoised") -> Optional[Path]:
    """
    Convenience function to create an unrotated trajectory with fixed chains.
    
    Args:
        output_dir: Directory containing trajectory files
        record_id: Unique identifier for this trajectory
        fixed_chains: List of chain letters that should remain fixed
        reference_pdb: Path to reference PDB with original positions (optional)
        trajectory_type: Type of trajectory to process ("denoised" or "raw")
        
    Returns:
        Path to the unrotated trajectory file, or None if processing failed
    """
    processor = UnrotatedTrajectoryProcessor(output_dir, record_id)
    return processor.process_fixed_chains(fixed_chains, reference_pdb, trajectory_type)